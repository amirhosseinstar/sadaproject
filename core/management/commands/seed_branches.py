class Command(BaseCommand):
    help = 'شعب واقعی خانه کارگر را همراه با استان هر شعبه ثبت/به‌روزرسانی می‌کند'

    def handle(self, *args, **options):
        created_count = 0
        updated_count = 0
        for name, province in BRANCHES:
            branch, created = Branch.objects.get_or_create(name=name, defaults={'province': province})
            if created:
                created_count += 1
            elif branch.province != province:
                branch.province = province
                branch.save(update_fields=['province'])
                updated_count += 1

        self.stdout.write(self.style.SUCCESS(
            f'{created_count} شعبه‌ی جدید ساخته شد، {updated_count} شعبه‌ی موجود به‌روزرسانی شد (استان)'
        ))
